const SKIP = new Set(['stance', 'foot', 'kind', 'tail', 'mouth', 'disc', 'vane', 'teeth', 'segs', 'legs', 'ribs', 'toes', 'neckA', 'neckCurve', 'tailA', 'tailCurve', 'headA', 'tilt', 'dorsalPos', 'headFrac']);

/** multiplicative jitter of all numeric parameters (keeps species distinguishable but family-like) */
export function jitter(L: Look, r: Rng, amount = 0.1): void {
  const P = L.P as unknown as Record<string, unknown>;
  for (const k of Object.keys(P)) {
    const v = P[k];
    if (typeof v === 'number' && !SKIP.has(k)) P[k] = r.j(v, amount);
    else if (typeof v === 'number' && (k === 'neckA' || k === 'tailA' || k === 'headA')) P[k] = v + r.r(-6, 6);
  }
  const F = L.F as Record<string, unknown>;
  for (const k of Object.keys(F)) if (typeof F[k] === 'number') F[k] = r.j(F[k] as number, 0.15);
}
